const SQLite=require('better-sqlite3');
const PgNative=require('pg-native');
const fs=require('fs');
const path=require('path');

const sqlitePath=process.argv[2]||process.env.SQLITE_PATH||'/app/data/betting.db';
const url=process.env.DATABASE_URL;
if(!url)throw new Error('DATABASE_URL é obrigatório para a migração.');
if(!fs.existsSync(sqlitePath)){console.log('SQLite não encontrado em '+sqlitePath+'; nada a migrar.');process.exit(0)}

const sqlite=new SQLite(sqlitePath,{readonly:true});
const pg=new PgNative();pg.connectSync(url);

const transform=(sql)=>{
  let q=String(sql).trim().replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/ig,'INSERT INTO');
  q=q.replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/ig,'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  q=q.replace(/\bAUTOINCREMENT\b/ig,'');
  q=q.replace(/datetime\(\s*'now'\s*\)/ig,'CURRENT_TIMESTAMP');
  q=q.replace(/\bBOOLEAN\b/ig,'INTEGER');
  return q;
};
const exec=sql=>pg.querySync(transform(sql));
const tables=sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY CASE WHEN name='users' THEN 1 ELSE 2 END,id").all();

pg.querySync('BEGIN');
try{
  pg.querySync('SET session_replication_role = replica');
  for(const t of tables)exec(t.sql);
  for(const t of tables){
    const rows=sqlite.prepare('SELECT * FROM "'+t.name.replaceAll('"','""')+'"').all();
    if(!rows.length)continue;
    const cols=Object.keys(rows[0]);
    const quoted=cols.map(c=>'"'+c.replaceAll('"','""')+'"').join(',');
    for(const row of rows){
      const vals=cols.map((_,i)=>'$'+(i+1)).join(',');
      pg.querySync('INSERT INTO "'+t.name.replaceAll('"','""')+'" ('+quoted+') VALUES ('+vals+') ON CONFLICT DO NOTHING',cols.map(c=>row[c]));
    }
    console.log('Migrada '+t.name+': '+rows.length+' registos');
  }
  for(const t of tables){
    const seqs=sqlite.prepare("SELECT name FROM sqlite_master WHERE type='table' AND sql LIKE '%AUTOINCREMENT%' AND name=?").all(t.name);
    if(seqs.length){
      const idRow=sqlite.prepare('SELECT MAX(id) max_id FROM "'+t.name.replaceAll('"','""')+'"').get();
      if(idRow?.max_id!=null)pg.querySync('SELECT setval(pg_get_serial_sequence($1,$2),$3,true)',[''+t.name,'id',Number(idRow.max_id)]);
    }
  }
  pg.querySync('SET session_replication_role = origin');
  pg.querySync('COMMIT');
  console.log('Migração SQLite → PostgreSQL concluída.');
}catch(e){
  try{pg.querySync('ROLLBACK')}catch{}
  throw e;
}finally{sqlite.close();pg.end();}
