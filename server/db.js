function createPostgres(url){
  const client=new PgNative();
  client.connectSync(url);
  let lastInsertRowid=0;
  const exec=(sql,params)=>{
    const statements=splitSqlStatements(pgSql(sql));
    try{
      let rows=[];
      for(const q of statements) rows=client.querySync(q,params||[])||rows;
      return rows;
    }catch(e){
      if(e?.code==='42701'){
        e.message='ERROR: duplicate column name: '+(e?.message||'column already exists');
      }
      throw e;
    }
  };
  const prepare=(sql)=>{
    const original=String(sql);
    return {
      all:(...params)=>exec(original,params),
      get:(...params)=>exec(original,params)[0],
      run:(...params)=>{
        let rows;
        try{
          let q=pgSql(original);
          if(!/\bRETURNING\b/i.test(q)&&/^INSERT\s+INTO\b/i.test(q)){
            const cols=q.match(/^INSERT\s+INTO\s+\w+\s*\(([^)]+)\)/i)?.[1]||'';
            if(!/\bid\b/i.test(cols)){
              try{rows=client.querySync(q+' RETURNING id',params||[])}catch(e){rows=client.querySync(q,params||[])}
            }else rows=client.querySync(q,params||[]);
          }else if(!/\bRETURNING\b/i.test(q)&&/^(UPDATE|DELETE)\b/i.test(q)){
            try{rows=client.querySync(q+' RETURNING 1',params||[])}catch(e){rows=client.querySync(q,params||[])}
          }else rows=client.querySync(q,params||[]);
        }catch(e){throw e}
        if(rows?.[0]?.id!=null)lastInsertRowid=Number(rows[0].id);
        return {changes:rows?.length||0,lastInsertRowid};
      }
    };
  };
  const db={
    prepare,exec:(sql)=>exec(sql),pragma:()=>null,
    transaction:(fn)=>()=>{exec('BEGIN');try{const r=fn();exec('COMMIT');return r}catch(e){try{exec('ROLLBACK')}catch{}throw e}},
    get lastInsertRowid(){return lastInsertRowid},
    close:()=>client.end()
  };
  return db;
}
