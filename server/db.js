const SQLite=require('better-sqlite3');
const PgNative=require('pg-native');

const quoteAwarePlaceholders=(sql)=>{
  let out='',n=0,single=false,double=false;
  for(let i=0;i<sql.length;i++){
    const ch=sql[i];
    if(ch==="'"&&!double){if(single&&sql[i+1]==="'"){out+="''";i++;continue}single=!single;out+=ch;continue}
    if(ch==='"'&&!single){double=!double;out+=ch;continue}
    if(ch==='?'&&!single&&!double){out+='$'+(++n);continue}
    out+=ch;
  }
  return out;
};
const pgSql=(sql)=>{
  let q=String(sql||'').trim();
  q=q.replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/ig,'INSERT INTO');
  if(/^INSERT\s+INTO\b/i.test(q)&&!/\bON\s+CONFLICT\b/i.test(q)){
    q=q.replace(/;\s*$/,'')+' ON CONFLICT DO NOTHING';
  }
  q=q.replace(/datetime\(\s*'now'\s*\)/ig,'CURRENT_TIMESTAMP');
  q=q.replace(/datetime\(\s*'now'\s*,\s*'([+-])([0-9]+)\s+(day|days|month|months|year|years)'\s*\)/ig,(_,sign,n,u)=>{
    const unit=u.startsWith('month')?'month':u.startsWith('year')?'year':'day';
    return `(CURRENT_TIMESTAMP ${sign==='-'?'-':'+'} INTERVAL '${n} ${unit}')`;
  });
  q=q.replace(/strftime\(\s*'%Y-%m'\s*,\s*([^)]+)\)/ig,"to_char(\\1::timestamp,'YYYY-MM')");
  q=q.replace(/strftime\(\s*'%Y-%W'\s*,\s*([^)]+)\)/ig,"to_char(\\1::timestamp,'IYYY-IW')");
  q=q.replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/ig,'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  q=q.replace(/\bINT\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/ig,'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  q=q.replace(/\bAUTOINCREMENT\b/ig,'');
  q=q.replace(/\bINSERT\s+OR\s+REPLACE\s+INTO\b/ig,'INSERT INTO');
  return quoteAwarePlaceholders(q);
};
const tableFromInsert=(sql)=>{const m=sql.match(/^INSERT\s+INTO\s+([A-Za-z0-9_]+)/i);return m?.[1]||null};

function createPostgres(url){
  const client=new PgNative();
  client.connectSync(url);
  let lastInsertRowid=0;
  const exec=(sql,params)=>{
    const q=pgSql(sql);
    const rows=client.querySync(q,params||[]);
    return rows||[];
  };
  const prepare=(sql)=>{
    const original=String(sql);
    return {
      all:(...params)=>exec(original,params),
      get:(...params)=>exec(original,params)[0],
      run:(...params)=>{
        let rows;
        try{
          let q=pgSql(original);
          if(/^INSERT\s+INTO\s+[A-Za-z0-9_]+\s*\(/i.test(q)&&!/\bRETURNING\b/i.test(q)){
            const table=tableFromInsert(q);
            if(table&&/\bid\b/i.test(q.match(/^INSERT\s+INTO\s+\w+\s*\(([^)]+)\)/i)?.[1]||'')===false){
              try{rows=client.querySync(q+' RETURNING id',params||[])}catch(e){rows=client.querySync(q,params||[])}
            }else rows=client.querySync(q,params||[]);
          }else rows=client.querySync(q,params||[]);
        }catch(e){throw e}
        if(rows?.[0]?.id!=null)lastInsertRowid=Number(rows[0].id);
        return {changes:rows?.length||0,lastInsertRowid};
      }
    };
  };
  const db={
    prepare,exec:(sql)=>exec(sql),pragma:()=>null,
    transaction:(fn)=>()=>{exec('BEGIN');try{const r=fn();exec('COMMIT');return r}catch(e){try{exec('ROLLBACK')}catch{}throw e}},
    get lastInsertRowid(){return lastInsertRowid},
    close:()=>client.end()
  };
  return db;
}
module.exports=(target)=>{
  const url=process.env.DATABASE_URL;
  if(url){
    console.log('Base de dados: PostgreSQL');
    return createPostgres(url);
  }
  console.log('Base de dados: SQLite (modo local/compatibilidade)');
  const db=new SQLite(target);db.pragma('journal_mode = WAL');return db;
};
