const quoteAwarePlaceholders=(sql)=>{
  let out='',n=0,single=false,double=false;
  for(let i=0;i<sql.length;i++){
    const ch=sql[i];
    if(ch==="'"&&!double){if(single&&sql[i+1]==="'"){out+="''";i++;continue}single=!single;out+=ch;continue}
    if(ch==='"'&&!single){double=!double;out+=ch;continue}
    if(ch==='?'&&!single&&!double){out+='$'+(++n);continue}
    out+=ch;
  }
  return out;
};
const pgSql=(sql)=>{
  let q=String(sql||'').trim();
  q=q.replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/ig,'INSERT INTO');
  q=q.replace(/\bALTER\s+TABLE\s+([A-Za-z0-9_]+)\s+ADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS\b)/ig,'ALTER TABLE $1 ADD COLUMN IF NOT EXISTS ');
  if(/^INSERT\s+INTO\b/i.test(q)&&!/\bON\s+CONFLICT\b/i.test(q)){
    q=q.replace(/;\s*$/,'')+' ON CONFLICT DO NOTHING';
  }
  q=q.replace(/datetime\(\s*'now'\s*\)/ig, "to_char(CURRENT_TIMESTAMP,'YYYY-MM-DD HH24:MI:SS')");
  q=q.replace(/datetime\(\s*'now'\s*,\s*'([+-])([0-9]+)\s+(day|days|month|months|year|years)'\s*\)/ig,(_,sign,n,u)=>{
    const unit=u.startsWith('month')?'month':u.startsWith('year')?'year':'day';
    return `to_char(CURRENT_TIMESTAMP ${sign==='-'?'-':'+'} INTERVAL '${n} ${unit}','YYYY-MM-DD HH24:MI:SS')`;
  });
  q=q.replace(/strftime\(\s*'%Y-%m'\s*,\s*([^)]+)\)/ig,"to_char(\\1::timestamp,'YYYY-MM')");
  q=q.replace(/strftime\(\s*'%Y-%W'\s*,\s*([^)]+)\)/ig,"to_char(\\1::timestamp,'IYYY-IW')");
  q=q.replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/ig,'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  q=q.replace(/\bAUTOINCREMENT\b/ig,'');
  q=q.replace(/\bAUTOINCREMENT\b/ig,'');
  q=q.replace(/(TEXT\s+DEFAULT)\s+CURRENT_TIMESTAMP\b/ig,"$1 (CURRENT_TIMESTAMP::text)");
  q=q.replace(/\bINSERT\s+OR\s+REPLACE\s+INTO\b/ig,'INSERT INTO');
  return quoteAwarePlaceholders(q);
};
